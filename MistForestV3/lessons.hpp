#pragma once // 预处理指令：同一编译单元只读取本头文件一次，避免重复定义。
#include <array> // 包含标准库头文件；std::array 用来保存长度固定的课程和答案。
#include <string> // 包含标准库头文件；std::wstring 用来保存 Windows 界面需要的宽字符中文。
namespace studio { // namespace 声明命名空间，把教学类型和函数集中在 studio 中，避免重名。
struct Lesson { // struct 定义结构体；它把一个教学关卡的文字和标准答案组合起来。
    std::wstring title; // std::wstring 是宽字符串类型；title 保存关卡标题，分号结束成员声明。
    std::wstring story; // story 保存已知的公开行动和自己的行动，不包含对方隐藏位置。
    std::wstring task; // task 保存需要玩家完成的问题；玩家用棋盘多选格子回答。
    std::wstring explanation; // explanation 保存提交后的解释，让玩家看到候选集合变化的原因。
    std::array<bool, 9> answer; // array<bool, 9> 是九个布尔值的定长数组；下标 0 至 8 对应格子 1 至 9。
}; // 右花括号结束结构体；结构体定义后必须有分号。
inline const std::array<Lesson, 3>& lessons() { // inline 允许头文件被多个源文件包含；const 引用返回三个只读关卡而不复制数据。
    static const std::array<Lesson, 3> content{{ // static 让数据只初始化一次；const 禁止修改，双花括号用于嵌套聚合初始化。
        { // 第一组花括号创建一个 Lesson；各项依次对应结构体中五个成员。
            L"第一课 · 攻击暴露位置", // L 前缀表示宽字符串字面量；此项初始化 title。
            L"你在9。对方刚攻击1，未命中，且本回合没有移动。此前没有其他位置线索。攻击只能选择自身格或上下左右邻格。", // 此项初始化 story；只给出自己位置和公开攻击，不提供对手真实位置。
            L"此刻对方可能在哪些格子？选全后提交。", // 此项初始化 task；要求选全候选位置，不是猜一个实际位置。
            L"答案：1、2、4。只有这三个格子能攻击1。5在1的斜角，不能攻击1；你在9，未命中不会额外排除对方位置。", // 此项初始化 explanation；说明攻击范围对称关系与未命中信息的含义。
            {{true, true, false, true, false, false, false, false, false}} // true 表示允许选择，false 表示应排除；依次对应格子 1、2、3、4、5、6、7、8、9。
        }, // 结束第一关；逗号分隔数组中的相邻元素。
        { // 第二个 Lesson 练习看到移动或等待提示后，怎样更新候选位置。
            L"第二课 · 移动更新线索", // 宽字符串标题；中文标点只是显示内容，不参与 C++ 语法。
            L"你在9，对方攻击1未命中，候选为1、2、4。你随后从9移到8，没有新线索。现在记录显示对方移动/等待，可能走一格，也可能原地不动。", // 自己的中间行动确保轮流顺序合法，公开提示不区分移动与等待。
            L"对方现在可能在哪？选出旧候选及其上下左右一步可达终点。", // 提醒玩家合并等待和移动两种可能性。
            L"答案：1、2、3、4、5、7。逐格更新：1→1/2/4；2→1/2/3/5；4→1/4/5/7，再合并。原地等待也是合法行动。", // 每个来源都保留原格，再合并相邻终点。
            {{true, true, true, true, true, false, true, false, false}} // 设置第二关标准答案；格子 6、8、9 不可能在这一步内到达。
        }, // 结束第二关；逗号表示后面还有第三关。
        { // 第三个 Lesson 组合自己的落空攻击和对方的攻击线索。
            L"第三课 · 合并两条证据", // 此宽字符串作为第三关标题显示在教学界面中。
            L"你在5，刚攻击2未命中。紧接着对方攻击1，也未命中；攻击不会移动角色。双方允许同格，只有命中才获胜。", // 自己从 5 攻击 2 合法；对方反击时没有移动，上一条排除证据因此仍然有效。
            L"结合这两条攻击记录，选出对方当前所有可能位置。", // 要求求候选集合的交集与排除结果，而非只看最近一次公开攻击。
            L"答案：1、4。对方攻击1，候选为1、2、4。你刚攻击2未命中，且对方没有移动，故排除2。你下一步能攻击4，不能攻击斜角的1。", // 给出逐步排除过程，并把位置推理连接到下一次合法行动。
            {{true, false, false, true, false, false, false, false, false}} // 设置第三关标准答案；只有格子 1 和 4 对应的布尔值为 true。
        } // 结束第三关；最后一个元素后可以不写逗号。
    }}; // 依次结束内层数组数据和外层 std::array 初始化；分号结束局部静态变量定义。
    return content; // return 返回已初始化数组的只读引用；静态存储期保证函数返回后数据仍然存在。
} // 结束 lessons 函数体。
} // 结束 studio 命名空间。
